constexpr uint32_t kNone = ~uint32_t{0};

// One qubit's wire: its last vertex and the type of the edge the next vertex
// attaches with (Hadamard after an odd number of basis changes).
struct Wire {
    Vertex last = 0;
    EdgeType pending = EdgeType::Simple;
};

// A Pauli on the HIR's qubits as per-qubit letters: bit q of x and z.
struct PauliLetters {
    std::vector<uint32_t> qubits;
    std::vector<uint8_t> letters;  // 1 = X, 2 = Z, 3 = Y
};

PauliLetters letters_of(const PauliString& pauli) {
    PauliLetters out;
    const MaskView x = pauli.x();
    const MaskView z = pauli.z();
    for (uint32_t q = 0; q < pauli.num_qubits(); ++q) {
        const auto letter = static_cast<uint8_t>(x.bit_get(q) | (z.bit_get(q) << 1));
        if (letter != 0) {
            out.qubits.push_back(q);
            out.letters.push_back(letter);
        }
    }
    return out;
}

// Resets on fresh qubits, as a rewrite of later Paulis.
//
// A traced reset of a used qubit is a measurement of a signed Pauli P whose
// outcome then controls a correction C that anticommutes with P. Afterwards
// the reset qubit, with Pauli group generated by P and C, is in the P = +1
// state and no longer correlated with anything. Its role passes to a fresh
// qubit n through the isomorphism P -> Z_n, C -> X_n that fixes everything
// commuting with P and C:
//
//   M -> M C^b P^a Z_n^a X_n^b,  a = [M anticommutes with C], b = [M anticommutes with P].
//
// Every later Pauli then commutes with P and C, so the old qubit is never
// touched again and the reset is a cut wire in the diagram. This is what
// tracing the circuit with a fresh qubit per reset gives, up to a Clifford on n.
class ResetFrame {
  public:
    ResetFrame(uint32_t hir_qubits, uint32_t width) : hir_qubits_(hir_qubits), width_(width) {}

    [[nodiscard]] PauliString lift(PauliMaskView mask) const {
        PauliString out(width_);
        for (uint32_t q = 0; q < hir_qubits_; ++q) {
            out.set_pauli(q, mask.x().bit_get(q), mask.z().bit_get(q));
        }
        out.set_sign(mask.sign());
        for (const Rewrite& rw : rewrites_) {
            const bool a = !out.view().commutes(rw.c.view());
            const bool b = !out.view().commutes(rw.p.view());
            if (b) {
                out.right_multiply(rw.c.view());
            }
            if (a) {
                out.right_multiply(rw.p.view());
                out.right_multiply(rw.z.view());
            }
            if (b) {
                out.right_multiply(rw.x.view());
            }
        }
        assert(out.is_hermitian());
        return out;
    }

    // `p` is the measured signed Pauli and `c` the correction, both lifted.
    void add_reset(PauliString p, PauliString c) {
        const uint32_t fresh = hir_qubits_ + static_cast<uint32_t>(rewrites_.size());
        assert(fresh < width_);
        if (!c.is_hermitian()) {
            c.add_phase(1);  // only C's commutation and its role as X_n matter
        }
        PauliString z(width_), x(width_);
        z.set_pauli(fresh, false, true);
        x.set_pauli(fresh, true, false);
        rewrites_.push_back(Rewrite{std::move(p), std::move(c), std::move(z), std::move(x)});
    }

  private:
    struct Rewrite {
        PauliString p, c, z, x;
    };

    uint32_t hir_qubits_;
    uint32_t width_;
    std::vector<Rewrite> rewrites_;
};

class Builder {
  public:
    explicit Builder(uint32_t num_qubits) : wires_(num_qubits) {
        for (Wire& w : wires_) {
            w.last = d_.graph.add_vertex(VertexType::X);  // |0>
        }
    }

    uint32_t new_param(DiagramParam::Kind kind, uint32_t index) {
        d_.params.push_back(DiagramParam{.kind = kind, .index = index});
        return static_cast<uint32_t>(d_.params.size() - 1);
    }

    Vertex append(uint32_t q, VertexType type, Phase phase) {
        Wire& w = wires_[q];
        const Vertex v = d_.graph.add_vertex(type, std::move(phase));
        d_.graph.add_edge(w.last, v, w.pending);
        w.last = v;
        w.pending = EdgeType::Simple;
        return v;
    }

    void hadamard(uint32_t q) { wires_[q].pending = toggled(wires_[q].pending); }

    // Z spiders on the support of P, one per qubit, in the basis that turns P
    // into a product of Z: X through a Hadamard, Y through S_DAG then a
    // Hadamard (S^dag Y S = X). `attach` joins each to the operation's hub.
    template <typename Attach>
    void z_legs(const PauliLetters& p, Attach attach) {
        for (size_t i = 0; i < p.qubits.size(); ++i) {
            const uint32_t q = p.qubits[i];
            const uint8_t letter = p.letters[i];
            if (letter == 3) {
                append(q, VertexType::Z, Phase(1.5));
            }
            if (letter != 2) {
                hadamard(q);
            }
            attach(append(q, VertexType::Z, Phase{}));
            if (letter != 2) {
                hadamard(q);
            }
            if (letter == 3) {
                append(q, VertexType::Z, Phase(0.5));
            }
        }
    }

    // exp(-i pi half_turns P / 2): legs into an X hub carrying a Z(half_turns) leaf.
    void rotation(const PauliLetters& p, double half_turns) {
        if (p.qubits.empty()) {
            return;  // a global phase
        }
        const Vertex hub = d_.graph.add_vertex(VertexType::X);
        z_legs(p, [&](Vertex leg) { d_.graph.add_edge(leg, hub, EdgeType::Simple); });
        const Vertex leaf = d_.graph.add_vertex(VertexType::Z, Phase(half_turns));
        d_.graph.add_edge(hub, leaf, EdgeType::Simple);
    }

    // The projector onto the (-1)^parity eigenspace of P: legs into an X hub
    // with phase pi * parity.
    void projector(const PauliLetters& p, const Phase& parity) {
        const Vertex hub = d_.graph.add_vertex(VertexType::X, parity);
        z_legs(p, [&](Vertex leg) { d_.graph.add_edge(leg, hub, EdgeType::Simple); });
    }

    // P applied when the parity is 1; a Y applies Z then X, which differ by a
    // trajectory-wide phase.
    void conditional_pauli(const PauliLetters& p, const Params& parity) {
        for (size_t i = 0; i < p.qubits.size(); ++i) {
            if (p.letters[i] & 2) {
                append(p.qubits[i], VertexType::Z, Phase(0.0, parity));
            }
            if (p.letters[i] & 1) {
                append(p.qubits[i], VertexType::X, Phase(0.0, parity));
            }
        }
    }

    void finish() {
        for (uint32_t q = 0; q < wires_.size(); ++q) {
            const uint32_t f = new_param(DiagramParam::Kind::Final, q);
            const Vertex leaf = d_.graph.add_vertex(VertexType::X, Phase(0.0, Params({f})));
            d_.graph.add_edge(wires_[q].last, leaf, wires_[q].pending);
        }
    }

    SingleCopyDiagram& diagram() { return d_; }

  private:
    SingleCopyDiagram d_;
    std::vector<Wire> wires_;
};

// Express each channel Pauli over a GF(2) basis of the site's channel Paulis.
// The basis vectors are channel Paulis themselves, so applying basis Pauli k
// when bit k is set reproduces every channel up to a phase.
struct SiteBasis {
    std::vector<PauliLetters> paulis;
    std::vector<uint64_t> patterns;  // one per channel
};

std::optional<SiteBasis> site_basis(const NoiseSite& site, const std::vector<PauliString>& masks) {
    // Symplectic vectors as bit arrays, x bits then z bits. Each echelon row
    // keeps the combination of basis Paulis it equals, so a channel that
    // reduces to zero is that combination of the basis.
    struct Row {
        std::vector<uint8_t> bits;
        uint64_t combination;
    };
    std::vector<Row> reduced;
    std::vector<uint32_t> pivots;
    SiteBasis basis;
    for (size_t ch = 0; ch < site.channels.size(); ++ch) {
        if (site.channels[ch].prob == 0.0) {
            // Kept as an outcome so outcomes stay one to one with channels,
            // but it never fires, so it needs no bit.
            basis.patterns.push_back(0);
            continue;
        }
        const PauliString& mask = masks[ch];
        const uint32_t n = mask.num_qubits();
        std::vector<uint8_t> v(2 * n, 0);
        for (uint32_t q = 0; q < n; ++q) {
            v[q] = static_cast<uint8_t>(mask.x().bit_get(q));
            v[n + q] = static_cast<uint8_t>(mask.z().bit_get(q));
        }
        uint64_t combination = 0;
        for (size_t r = 0; r < reduced.size(); ++r) {
            if (v[pivots[r]]) {
                for (size_t k = 0; k < v.size(); ++k) {
                    v[k] ^= reduced[r].bits[k];
                }
                combination ^= reduced[r].combination;
            }
        }
        uint32_t pivot = kNone;
        for (uint32_t k = 0; k < v.size(); ++k) {
            if (v[k]) {
                pivot = k;
                break;
            }
        }
        if (pivot == kNone) {
            basis.patterns.push_back(combination);
            continue;
        }
        if (basis.paulis.size() == 64) {
            return std::nullopt;
        }
        const uint64_t bit = uint64_t{1} << basis.paulis.size();
        basis.paulis.push_back(letters_of(mask));
        reduced.push_back(Row{.bits = std::move(v), .combination = combination ^ bit});
        pivots.push_back(pivot);
        basis.patterns.push_back(bit);
    }
    return basis;
}

// The measurement at `i` and the adjacent corrections it controls form a
// reset when the corrections' product anticommutes with the measured Pauli.
// Returns one past the last correction, or i + 1 if it is no reset.
size_t reset_end(const HirModule& hir, size_t i) {
    const HeisenbergOp& m = hir.ops[i];
    const auto r = static_cast<uint32_t>(m.meas_record_idx());
    const PauliMaskView p = hir.mask_view(m);
    size_t end = i + 1;
    bool anticommutes = false;
    while (end < hir.ops.size() && hir.ops[end].op_type() == OpType::CONDITIONAL_PAULI &&
           static_cast<uint32_t>(hir.ops[end].controlling_meas()) == r) {
        const PauliMaskView c = hir.mask_view(hir.ops[end]);
        anticommutes ^= anti_commute(c.x(), c.z(), p.x(), p.z());
        ++end;
    }
    return anticommutes ? end : i + 1;
}

