std::optional<SingleCopyDiagram> build_single_copy_diagram(const HirModule& hir,
                                                           std::string* reason,
                                                           uint32_t max_qubits) {
    auto reject = [&](std::string why) -> std::optional<SingleCopyDiagram> {
        if (reason) {
            *reason = std::move(why);
        }
        return std::nullopt;
    };
    // The planner corrects a reordered op's sign by the noise it crossed; the
    // diagram reads noise at its position in the op list instead.
    if (hir.has_logical_noise_prefix() && !hir.logical_noise_prefix_matches_schedule()) {
        return reject("noise has been rescheduled past other operations");
    }
    const uint32_t num_records = hir.num_measurements + hir.num_hidden_measurements;
    // A readout flip enters the diagram only if feedback reads the flipped
    // record; otherwise it is a classical flip of the record, applied outside
    // the diagram (and may then be asymmetric).
    std::vector<size_t> last_read(num_records, 0);
    std::vector<bool> read(num_records, false);
    for (size_t i = 0; i < hir.ops.size(); ++i) {
        if (hir.ops[i].op_type() == OpType::CONDITIONAL_PAULI) {
            const auto r = static_cast<uint32_t>(hir.ops[i].controlling_meas());
            if (r >= num_records) {
                return reject("feedback names an unknown record");
            }
            last_read[r] = i;
            read[r] = true;
        }
    }
    std::vector<bool> in_diagram(hir.readout_noise.size(), false);
    for (size_t i = 0; i < hir.ops.size(); ++i) {
        if (hir.ops[i].op_type() != OpType::READOUT_NOISE) {
            continue;
        }
        const auto k = static_cast<uint32_t>(hir.ops[i].readout_noise_idx());
        if (k >= hir.readout_noise.size() || hir.readout_noise[k].meas_idx >= num_records) {
            return reject("readout noise names an unknown entry or record");
        }
        const uint32_t r = hir.readout_noise[k].meas_idx;
        in_diagram[k] = read[r] && last_read[r] > i;
        if (in_diagram[k] && !hir.readout_noise[k].is_symmetric()) {
            return reject("feedback reads a record with asymmetric readout noise");
        }
    }

    // One fresh qubit per reset; see ResetFrame.
    std::vector<size_t> reset_ends(hir.ops.size(), 0);
    uint32_t num_resets = 0;
    for (size_t i = 0; i < hir.ops.size(); ++i) {
        if (hir.ops[i].op_type() == OpType::MEASURE) {
            reset_ends[i] = reset_end(hir, i);
            num_resets += reset_ends[i] > i + 1;
        }
    }
    if (uint64_t{hir.num_qubits} + num_resets > max_qubits) {
        return reject("fresh qubits for resets would exceed the qubit limit");
    }
    const uint32_t width = hir.num_qubits + num_resets;
    ResetFrame frame(hir.num_qubits, width);

    Builder b(width);
    SingleCopyDiagram& d = b.diagram();
    // Parameter IDs: record and hidden outcomes first, by record index.
    for (uint32_t r = 0; r < num_records; ++r) {
        b.new_param(
            r < hir.num_measurements ? DiagramParam::Kind::Record : DiagramParam::Kind::Hidden, r);
    }
    std::vector<uint32_t> readout_bit(hir.readout_noise.size(), kNone);
    std::vector<std::vector<uint32_t>> readout_of_record(num_records);
    for (uint32_t k = 0; k < hir.readout_noise.size(); ++k) {
        const ReadoutNoiseEntry& entry = hir.readout_noise[k];
        if (!in_diagram[k]) {
            if (entry.prob_zero_to_one != 0.0 || entry.prob_one_to_zero != 0.0) {
                d.classical_readout.push_back(k);
            }
            continue;
        }
        if (entry.prob_zero_to_one == 0.0) {
            continue;
        }
        const uint32_t group = static_cast<uint32_t>(d.noise.size());
        readout_bit[k] = b.new_param(DiagramParam::Kind::Noise, group);
        readout_of_record[entry.meas_idx].push_back(readout_bit[k]);
        d.noise.push_back(
            NoiseGroup{.source = NoiseGroup::Source::Readout,
                       .source_index = k,
                       .bits = {readout_bit[k]},
                       .outcomes = {{.probability = 1.0 - entry.prob_zero_to_one, .pattern = 0},
                                    {.probability = entry.prob_zero_to_one, .pattern = 1}}});
    }
    // The record parameter is the value after every in-diagram flip. A
    // record's current value is the physical outcome XOR the flips applied so
    // far: it starts as the parameter XOR every in-diagram flip, and each of
    // their READOUT_NOISE ops removes its flip.
    std::vector<Params> current(num_records);
    for (uint32_t r = 0; r < num_records; ++r) {
        std::vector<uint32_t> ids = {r};
        ids.insert(ids.end(), readout_of_record[r].begin(), readout_of_record[r].end());
        current[r] = Params(std::move(ids));
    }
    std::vector<bool> written(num_records, false);

    for (size_t i = 0; i < hir.ops.size(); ++i) {
        const HeisenbergOp& op = hir.ops[i];
        switch (op.op_type()) {
            case OpType::T_GATE:
            case OpType::PHASE_ROTATION: {
                const PauliString axis = frame.lift(hir.mask_view(op));
                double half_turns =
                    op.op_type() == OpType::T_GATE ? (op.is_dagger() ? -0.25 : 0.25) : op.alpha();
                if (axis.sign()) {
                    half_turns = -half_turns;
                }
                b.rotation(letters_of(axis), half_turns);
                break;
            }
            case OpType::MEASURE: {
                const auto r = static_cast<uint32_t>(op.meas_record_idx());
                if (r >= num_records || written[r]) {
                    return reject("measurement names an unknown or repeated record");
                }
                written[r] = true;
                PauliString measured = frame.lift(hir.mask_view(op));
                b.projector(letters_of(measured), Phase(measured.sign() ? 1.0 : 0.0, current[r]));
                if (reset_ends[i] > i + 1) {
                    // The corrections act on the reset qubit only once later
                    // Paulis are rewritten, and nothing reads that qubit again.
                    PauliString correction(width);
                    for (size_t j = i + 1; j < reset_ends[i]; ++j) {
                        correction.right_multiply(frame.lift(hir.mask_view(hir.ops[j])).view());
                    }
                    frame.add_reset(std::move(measured), std::move(correction));
                    i = reset_ends[i] - 1;
                }
                break;
            }
            case OpType::CONDITIONAL_PAULI: {
                const auto r = static_cast<uint32_t>(op.controlling_meas());
                if (!written[r]) {
                    return reject("feedback reads a record before its measurement");
                }
                b.conditional_pauli(letters_of(frame.lift(hir.mask_view(op))), current[r]);
                break;
            }
            case OpType::NOISE: {
                const auto s = static_cast<uint32_t>(op.noise_site_idx());
                if (s >= hir.noise_sites.size()) {
                    return reject("noise names an unknown site");
                }
                const NoiseSite& site = hir.noise_sites[s];
                std::vector<PauliString> masks;
                masks.reserve(site.channels.size());
                for (const NoiseChannel& channel : site.channels) {
                    masks.push_back(frame.lift(hir.noise_channel_masks.at(channel.mask)));
                }
                const std::optional<SiteBasis> basis = site_basis(site, masks);
                if (!basis) {
                    return reject("noise site has more than 64 independent channels");
                }
                NoiseGroup group{.source = NoiseGroup::Source::NoiseSite,
                                 .source_index = s,
                                 .bits = {},
                                 .outcomes = {}};
                const uint32_t group_index = static_cast<uint32_t>(d.noise.size());
                for (const PauliLetters& p : basis->paulis) {
                    const uint32_t bit = b.new_param(DiagramParam::Kind::Noise, group_index);
                    group.bits.push_back(bit);
                    b.conditional_pauli(p, Params({bit}));
                }
                double fired = 0.0;
                for (size_t c = 0; c < site.channels.size(); ++c) {
                    group.outcomes.push_back(
                        {.probability = site.channels[c].prob, .pattern = basis->patterns[c]});
                    fired += site.channels[c].prob;
                }
                // Rounding can leave the sum a hair above 1.
                group.outcomes.insert(group.outcomes.begin(),
                                      {.probability = std::max(0.0, 1.0 - fired), .pattern = 0});
                d.noise.push_back(std::move(group));
                break;
            }
            case OpType::READOUT_NOISE: {
                const auto k = static_cast<uint32_t>(op.readout_noise_idx());
                if (!written[hir.readout_noise[k].meas_idx]) {
                    return reject("readout noise flips a record before its measurement");
                }
                if (readout_bit[k] != kNone) {
                    current[hir.readout_noise[k].meas_idx].xor_with(Params({readout_bit[k]}));
                }
                break;
            }
            case OpType::DETECTOR:
            case OpType::OBSERVABLE:
                break;
            case OpType::EXP_VAL:
                return reject("expectation-value probes name physical qubits");
            case OpType::INSTRUMENT:
                return reject("leakage and loss instruments are not Pauli operations");
            case OpType::NUM_OP_TYPES:
                assert(false && "sentinel op type");
                break;
        }
    }
    b.finish();
    return std::move(b.diagram());
}

